static void oled_char(uint8_t col, uint8_t page, char c)
{
    if (c < 32 || c > 94) return;
    const uint8_t *glyph = font6x8[c - 32];
    oled_set_pos(page, col);
    uint8_t buf[7]; buf[0] = 0x40;
    for (int i = 0; i < 6; i++) buf[i + 1] = glyph[i];
    i2c_transmitBlocking(I2C0_BUS, OLED_ADDR, buf, 7);
}

/* --- 公开 API --- */
void oled_init(void)
{
    oled_i2c_hw_init();
    delay_ms(50);

    uint8_t cmds[] = {
        0xAE, 0x20,0x00, 0x40, 0xA1, 0xC8, 0xDA,0x12,
        0x81,0x7F, 0xA4, 0xA6, 0xD9,0xF1, 0xDB,0x40,
        0x8D,0x14, 0x2E, 0xAF,
    };
    for (uint32_t i = 0; i < sizeof(cmds); i++) oled_cmd(cmds[i]);
    delay_ms(10);
}

void oled_clear(void)
{
    uint8_t zero[128] = {0};
    for (int pg = 0; pg < 8; pg++) { oled_set_pos(pg, 0); oled_data(zero, 128); }
}

void oled_chess(void)
{
    uint8_t row[128];
    for (int pg = 0; pg < 8; pg++) {
        for (int i = 0; i < 128; i++) row[i] = ((i/8+pg)%2) ? 0xFF : 0x00;
        oled_set_pos(pg, 0); oled_data(row, 128);
    }
}

void oled_text(uint8_t col, uint8_t page, const char *str)
{
    while (*str) { oled_char(col, page, *str); col += 6; str++; }
}
