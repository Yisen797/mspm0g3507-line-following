/**
 * @file    oled_ssd1306.c
 * @brief   SSD1306 OLED I2C 驱动 — PA0(SDA) + PA1(SCL)
 *
 * I2C0, PF3, 7-bit 地址 0x3C
 * PA0/PA1 是芯片默认 BSL I2C 引脚, 开漏结构, 需外接 4.7kΩ 上拉 (OLED模块自带)
 */

#include "oled_ssd1306.h"
#include "delay.h"
#include "i2c_blocking.h"

#define OLED_ADDR  0x3C

/* --- I2C 硬件初始化 (参考 TI 官方 i2c_controller_rw_multibyte_fifo_poll 示例) --- */
static void oled_i2c_hw_init(void)
{
    DL_GPIO_reset(GPIOA);
    DL_GPIO_enablePower(GPIOA);

    DL_I2C_reset(I2C0_BUS);
    DL_I2C_enablePower(I2C0_BUS);
    delay_cycles(16);  /* POWER_STARTUP_DELAY */

    i2c_initController(I2C0_BUS,
        IOMUX_PINCM1, IOMUX_PINCM1_PF_I2C0_SDA,
        IOMUX_PINCM2, IOMUX_PINCM2_PF_I2C0_SCL,
        7);   /* 400kHz @ 32MHz BUSCLK */
}

/* --- 底层通信 --- */
static void oled_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    i2c_transmitBlocking(I2C0_BUS, OLED_ADDR, buf, 2);
}

static void oled_set_pos(uint8_t page, uint8_t col)
{
    oled_cmd(0xB0 | (page & 7));
    oled_cmd(0x00 | (col & 0x0F));
    oled_cmd(0x10 | ((col >> 4) & 0x0F));
}

static void oled_data(const uint8_t *data, int len)
{
    uint8_t buf[129];
    int sent = 0;
    while (sent < len) {
        int chunk = (len - sent > 128) ? 128 : (len - sent);
        buf[0] = 0x40;
        for (int i = 0; i < chunk; i++) buf[i + 1] = data[sent + i];
        i2c_transmitBlocking(I2C0_BUS, OLED_ADDR, buf, chunk + 1);
        sent += chunk;
    }
}

